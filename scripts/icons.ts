import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Generates src/lib/ui/icon/icons.ts: the lucide icons src/ imports from
// icon/icons, as plain SVG node data drawn by one Icon component. A Svelte
// component per icon (what @lucide/svelte ships) costs several times more of
// the firmware budget. Run after using a new icon: `pnpm icons`.

function files(dir: string): string[] {
  const out: string[] = [];
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) out.push(...files(p));
    else if (p.endsWith('.svelte') || p.endsWith('.ts')) out.push(p);
  }
  return out;
}

const used = new Set<string>();
for (const file of files('src')) {
  for (const m of readFileSync(file, 'utf8').matchAll(
    /import\s*\{([^}]*)\}\s*from\s*'[./a-z]*icon\/icons'/g,
  )) {
    for (const name of (m[1] ?? '').split(','))
      if (name.trim()) used.add(name.trim());
  }
}

const kebab = (name: string) =>
  name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const lines = [...used].sort().map((name) => {
  const source = readFileSync(
    `node_modules/@lucide/svelte/dist/icons/${kebab(name)}.svelte`,
    'utf8',
  );
  const data = /const iconData = (\{.*\});/.exec(source)?.[1];
  if (!data) throw new Error(`no lucide icon ${name}`);
  const { node } = JSON.parse(data) as { node: unknown };
  return `export const ${name}: IconNode = ${JSON.stringify(node)};`;
});

writeFileSync(
  'src/lib/ui/icon/icons.ts',
  `// Generated by scripts/icons.ts from @lucide/svelte (ISC licence). Do not edit.\nimport type { IconNode } from './types';\n\n${lines.join('\n')}\n`,
);
console.log(`icons: ${String(lines.length)}`);

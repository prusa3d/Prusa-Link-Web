import { mkdirSync } from 'node:fs';

import { zipSync } from 'fflate';
import {
  chromium,
  devices,
  type BrowserContextOptions,
  type Page,
} from 'playwright';

// Walkthroughs against the mock printer (.claude/skills/record-demo).
// Usage: record-demo.ts <base url> <out dir> <phone|desktop|dev>

const base = process.argv[2] ?? 'http://localhost:5961';
const out = process.argv[3] ?? '.video/out';
const mode = process.argv[4] ?? 'phone';
const pause = (ms: number) =>
  new Promise((resolve) => {
    setTimeout(resolve, ms);
  });

const browser = await chromium.launch();

/// A plain G-code file the way PrusaSlicer writes it: a PNG thumbnail at the
/// top, the settings at the bottom. The app reads both in the browser.
async function slicedGcode(name: string, color: string, minutes: number) {
  const page = await browser.newPage({ viewport: { width: 313, height: 173 } });
  await page.setContent(
    `<body style="margin:0;background:#f2f2f3;display:grid;place-items:center;height:173px">
     <div style="width:120px;height:80px;border-radius:14px;background:${color};box-shadow:0 18px 0 -6px #d7d7db"></div></body>`,
  );
  const png = (await page.screenshot()).toString('base64');
  await page.close();
  const lines = png.match(/.{1,78}/g) ?? [];
  const gcode = [
    '; generated by PrusaSlicer 2.9.2',
    `; thumbnail begin 313x173 ${String(png.length)}`,
    ...lines.map((l) => `; ${l}`),
    '; thumbnail end',
    'G28',
    'G1 X10 Y10 Z0.2 F3000',
    `; estimated printing time (normal mode) = ${String(Math.floor(minutes / 60))}h ${String(minutes % 60)}m 12s`,
    '; filament_type = PETG',
    '; printer_model = MK4S',
  ].join('\n');
  return {
    name,
    mimeType: 'application/octet-stream',
    buffer: Buffer.from(gcode),
  };
}

async function signIn(page: Page, apiKey: string) {
  await page.goto(base);
  await pause(1200);
  await page
    .getByLabel('PrusaLink password')
    .pressSequentially(apiKey, { delay: 60 });
  await pause(400);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByTestId('printer-name').waitFor();
  await pause(1800);
}

async function browse(page: Page) {
  const list = page.getByRole('list', { name: 'Files on the printer' });
  await list.getByRole('button', { name: 'toys' }).click();
  await pause(900);
  await list.getByRole('button', { name: 'dragons' }).click();
  await pause(1600);
  await page.getByRole('button', { name: 'Up one folder' }).click();
  await pause(500);
  await page.getByRole('button', { name: 'Up one folder' }).click();
  await pause(900);
}

async function printAndWatch(page: Page) {
  const dialog = page.getByRole('dialog');
  await dialog.waitFor();
  await pause(2500);
  await dialog.getByRole('button', { name: 'Print now' }).click();
  await page.evaluate(() => {
    window.scrollTo({ top: 0, behavior: 'smooth' });
  });
  await pause(4000);
  await page.getByRole('button', { name: 'Pause' }).click();
  await pause(2200);
  await page.getByRole('button', { name: 'Resume' }).click();
  await pause(6000);
}

async function record(
  options: BrowserContextOptions,
  run: (page: Page, apiKey: string) => Promise<void>,
) {
  mkdirSync(out, { recursive: true });
  const context = await browser.newContext({
    ...options,
    recordVideo: {
      dir: out,
      size: options.viewport ?? { width: 1280, height: 800 },
    },
  });
  await context.request.patch(`${base}/__mock/state`, {
    data: { model: 'MK4S', reset: true, timeScale: 150 },
  });
  const state = await context.request.get(`${base}/__mock/state`);
  const { apiKey } = (await state.json()) as { apiKey: string };
  const page = await context.newPage();
  await run(page, apiKey);
  await context.close();
}

const holder = await slicedGcode(
  'phone-holder_0.4n_0.2mm_PETG_MK4S_38m.gcode',
  '#2f80ed',
  38,
);

if (mode === 'phone') {
  await record({ ...devices['iPhone 13'] }, async (page, apiKey) => {
    await signIn(page, apiKey);
    await page.mouse.wheel(0, 300);
    await pause(800);
    await browse(page);
    // The phone picker shows every file; the app keeps the G-code only.
    await page.getByTestId('file-input').setInputFiles([
      holder,
      {
        name: 'IMG_2041.jpg',
        mimeType: 'image/jpeg',
        buffer: Buffer.from('x'),
      },
    ]);
    await printAndWatch(page);
  });
}

if (mode === 'desktop') {
  await record(
    { viewport: { width: 1280, height: 800 } },
    async (page, apiKey) => {
      await signIn(page, apiKey);
      await browse(page);
      // A ZIP dropped on the page: unpacked in the browser, G-code uploaded.
      const zip = zipSync({
        'project/lid_0.4n_0.2mm_PLA_MK4S_47m.gcode': new TextEncoder().encode(
          'G28\n',
        ),
        'project/base_0.4n_0.2mm_PLA_MK4S_1h12m.gcode':
          new TextEncoder().encode('G28\n'),
        'project/notes.txt': new TextEncoder().encode('notes'),
        '__MACOSX/project/._lid.gcode': new TextEncoder().encode('x'),
      });
      await page.evaluate(
        async ([bytes]) => {
          const data = new DataTransfer();
          data.items.add(
            new File([new Uint8Array(bytes ?? [])], 'enclosure-project.zip'),
          );
          const target = document.querySelector('label:has(input[type=file])');
          target?.dispatchEvent(
            new DragEvent('dragover', { dataTransfer: data, bubbles: true }),
          );
          await new Promise((r) => setTimeout(r, 900));
          target?.dispatchEvent(
            new DragEvent('drop', { dataTransfer: data, bubbles: true }),
          );
        },
        [Array.from(zip)],
      );
      await pause(3500);
      await page.getByTestId('file-input').setInputFiles([holder]);
      await printAndWatch(page);
    },
  );
}

if (mode === 'dev') {
  await record(
    { viewport: { width: 1440, height: 860 } },
    async (page, apiKey) => {
      await page.goto(`${base}/?panel#key=${apiKey}`);
      await page.getByTestId('printer-name').waitFor();
      const panel = page.getByRole('complementary', { name: 'Mock printer' });
      await pause(2000);
      for (const model of ['XL', 'COREONE', 'COREONE INDX', 'MK4S']) {
        await panel.getByRole('button', { name: model, exact: true }).click();
        await pause(1600);
      }
      await panel.getByRole('button', { name: '400×' }).click();
      await panel.getByRole('button', { name: /phone stand/ }).click();
      await pause(3500);
      for (const state of ['PAUSED', 'ATTENTION', 'ERROR', 'PRINTING']) {
        await panel.getByRole('button', { name: state, exact: true }).click();
        await pause(1800);
      }
      await pause(4000);
      await panel.getByRole('button', { name: 'Reset' }).click();
      await pause(2000);
    },
  );
}

await browser.close();
